// --------------------------------------------------------------------------
// Camera
// --------------------------------------------------------------------------

/**
 * A fully resolved camera instruction for one shot.
 *
 * These are numbers and enums, not prose. Prose is generated later by the
 * provider prompt adapter, so a model that prefers "dolly in slowly" and a
 * model that prefers "camera: push_in, speed 0.3" can both be served from the
 * same directive.
 */
export const CameraDirective = z.object({
  presetId: z.string().min(1),
  presetLabel: z.string().min(1),
  device: CameraDevice,
  shotSize: ShotSize,
  angle: CameraAngle,
  height: CameraHeight,
  /** Dominant movement for the shot. */
  primaryMove: CameraMove,
  /** Optional layered movement (e.g. push_in + handheld_drift). */
  secondaryMove: CameraMove.nullable().default(null),
  /** 0 = imperceptible, 1 = dramatic. Kept low by default on purpose. */
  moveIntensity: z.number().min(0).max(1),
  /** How fast the move completes across the shot. 0 = glacial, 1 = fast. */
  moveSpeed: z.number().min(0).max(1),
  /** 1 = locked off tripod, 0 = deliberately loose handheld. */
  stability: z.number().min(0).max(1),
  /** Sub-pixel breathing that sells "a human is holding this". */
  microJitter: z.number().min(0).max(1),
  /** Approximate full-frame-equivalent focal length. Drives perspective prose. */
  focalLengthMm: z.number().min(8).max(200),
  depthOfField: DepthOfField,
  focusBehavior: FocusBehavior,
  /** Metres from lens to hero subject. Drives framing and DoF language. */
  subjectDistanceM: z.number().min(0.05).max(30),
  /** How much foreground/background separation the move should reveal. */
  parallax: z.number().min(0).max(1),
  framingNotes: z.string().max(400).default(""),
  /** Why the camera director chose this. Shown in the plan inspector. */
  rationale: z.string().max(400).default(""),
});
export type CameraDirective = z.infer<typeof CameraDirective>;

