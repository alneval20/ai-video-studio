export const REALISM_DOMAINS = [
  "human_anatomy",
  "hands",
  "facial_identity",
  "food_texture",
  "liquid_physics",
  "product_geometry",
  "branding_legibility",
  "material_texture",
  "lighting_physics",
  "camera_optics",
  "motion_physics",
  "temporal_stability",
  "scene_coherence",
] as const;
export const RealismDomain = z.enum(REALISM_DOMAINS);
export type RealismDomain = z.infer<typeof RealismDomain>;

export const RealismDirective = z.object({
  level: RealismLevel,
  /** Per-domain strictness. `off` domains are never mentioned in prompts. */
  emphasis: z.record(RealismDomain, Strictness),
  /** Affirmative realism statements, already ordered by importance. */
  positives: z.array(z.string().min(1)),
  /** Negative constraints — what the model must avoid. */
  negatives: z.array(z.string().min(1)),
  /** Ids of the catalogue rules that fired. Useful for debugging the engine. */
  appliedRuleIds: z.array(z.string()),
});
export type RealismDirective = z.infer<typeof RealismDirective>;

