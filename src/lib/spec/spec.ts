/**
 * VideoGenerationSpec — the normalised internal representation of a video.
 *
 * Every downstream system (prompt compiler, provider adapters, quality control,
 * composer) reads this and nothing else. Raw user text appears exactly once,
 * in `source.prompt`, and is never re-parsed.
 */
export const VideoGenerationSpec = z.object({
  specVersion: z.literal(SPEC_VERSION),
  id: z.string().min(1),
  projectId: z.string().min(1),
  createdAt: z.string().min(1),

  source: z.object({
    prompt: z.string(),
    language: z.string(),
    brandProfileId: z.string().nullable().default(null),
  }),

  creative: z.object({
    logline: z.string().min(1),
    visualStyle: VisualStyle,
    colorGrade: ColorGrade,
    mood: Mood,
    socialArchetype: SocialArchetype,
    aestheticTags: z.array(z.string()).default([]),
  }),

  delivery: DeliverySpec,
  scene: SceneSpec,
  realism: RealismDirective,
  consistency: ConsistencyContract,
  references: z.array(ReferenceDirective).default([]),
  shots: z.array(Shot).min(1),
  quality: QualityTargets,
  provider: ProviderPreferences,
  post: PostProduction,

  /** Provenance of the brief that produced this spec. */
  brief: DirectorBrief,
  directorMeta: DirectorMeta,
});
export type VideoGenerationSpec = z.infer<typeof VideoGenerationSpec>;

/** Convenience: the hero subject, which most engines special-case. */
export function heroSubject(spec: VideoGenerationSpec): SceneSubject {
  return spec.scene.subjects.find((s) => s.hero) ?? spec.scene.subjects[0];
}

export function shotById(spec: VideoGenerationSpec, shotId: string): Shot | undefined {
  return spec.shots.find((s) => s.id === shotId);
}

/** References that apply to a given shot (global ones included). */
export function referencesForShot(spec: VideoGenerationSpec, shotId: string): ReferenceDirective[] {
  return spec.references.filter((r) => r.shotIds === null || r.shotIds.includes(shotId));
}
